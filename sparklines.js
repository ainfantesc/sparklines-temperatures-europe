const todos = seriesTemperatura.flatMap(p => p.datos.map(d => d.valor));
const minimo = Math.floor(Math.min(...todos)*2)/2 - 0.1;
const maximo = Math.ceil(Math.max(...todos)*2)/2 + 0.1;
const formato = n => (n >= 0 ? '+' : '') + n.toFixed(2).replace('.', ',') + ' °C';
const contenedor = document.getElementById('filas');
const instancias = [];
seriesTemperatura.forEach(p => {
  const primero = p.datos[0].valor;
  const ultimo = p.datos[p.datos.length-1].valor;
  const fila = document.createElement('div'); fila.className = 'fila';
  const nombre = document.createElement('strong'); nombre.textContent = p.pais;
  const grafico = document.createElement('div'); grafico.className = 'spark';
  const actual = document.createElement('span'); actual.textContent = formato(ultimo);
  const diferencia = document.createElement('span'); diferencia.textContent = (ultimo-primero >= 0 ? '+' : '') + (ultimo-primero).toFixed(2).replace('.', ',') + ' °C';
  fila.append(nombre,grafico,actual,diferencia); contenedor.appendChild(fila);
  const chart = echarts.init(grafico);
  chart.setOption({animation:false,grid:{top:8,bottom:8,left:3,right:3},
    xAxis:{type:'category',show:false,data:p.datos.map(d=>d.anio),boundaryGap:false},
    yAxis:{type:'value',show:false,min:minimo,max:maximo},
    tooltip:{trigger:'axis',confine:true,formatter:params => `${p.pais} · ${params[0].axisValue}<br/><b>${formato(params[0].value)}</b>`},
    series:[{type:'line',data:p.datos.map(d=>d.valor),showSymbol:false,smooth:false,lineStyle:{width:2.4,color:'#2374AB'},itemStyle:{color:'#2374AB'},markLine:{silent:true,symbol:'none',label:{show:false},lineStyle:{color:'#9CA3AF',type:'dashed',width:1},data:[{yAxis:0}]} }]
  }); instancias.push(chart);
});
window.addEventListener('resize',()=>instancias.forEach(c=>c.resize()));
